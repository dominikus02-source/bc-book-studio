"use strict";
const assert=require("node:assert/strict");
const {randomBytes,createHash}=require("node:crypto");
const {PrismaClient}=require("@prisma/client");
const {chromium}=require("playwright");
const database=new URL(process.env.DATABASE_URL);
assert.equal(database.host+database.pathname,"127.0.0.1:55999/bookstudio_import_qa");
const db=new PrismaClient();
const origin="http://127.0.0.1:32979";
let user,book,browser;
async function main(){
 user=await db.studioUser.create({data:{role:"ADMIN",active:true,name:"Recovery QA",email:randomBytes(12).toString("hex")+"@example.invalid"}});
 const token=randomBytes(32).toString("hex");
 await db.studioSession.create({data:{userId:user.id,tokenHash:createHash("sha256").update(token).digest("hex"),expiresAt:new Date(Date.now()+600000)}});
 book=await db.book.create({data:{ownerId:user.id,title:"Recovery QA",grade:"7",subject:"Bahasa",chapters:{create:{position:1,title:"Bab pemulihan",content:"Isi awal yang tersimpan di server untuk pengujian."}}},include:{chapters:true}});
 const chapter=book.chapters[0], path="/api/books/"+book.id+"/chapters/"+chapter.id;
 const key="bcstudio:canvas-draft:"+book.id+":"+chapter.id;
 browser=await chromium.launch();
 const context=await browser.newContext({viewport:{width:390,height:844},acceptDownloads:true});
 await context.addCookies([{name:"bcstudio_session",value:token,url:origin}]);
 const page=await context.newPage();
 page.on("dialog",dialog=>dialog.accept());
 const canvas=page.locator("section.writing-workspace");
 const field=canvas.getByLabel("Isi paragraf 1");
 const recovery=canvas.getByRole("region",{name:"Pemulihan draf kanvas"});
 const url=origin+"/studio?module=Studio+Penulisan&bookId="+book.id;
 await page.goto(url);
 await field.waitFor({timeout:60000});
 let block=true;
 await page.route("**"+path,async route=>{
  if(block&&route.request().method()==="PATCH")await route.fulfill({status:503,contentType:"application/json",body:JSON.stringify({error:"Gangguan simpan QA"})});
  else await route.continue();
 });
 const draft="Draf lokal yang wajib bertahan setelah gangguan jaringan dan refresh.";
 await field.fill(draft);
 await canvas.getByText("Gangguan simpan QA",{exact:true}).waitFor();
 await page.reload();
 await recovery.waitFor();
 assert.equal(await field.isDisabled(),true);
 assert.equal((await db.chapter.findUnique({where:{id:chapter.id}})).content,chapter.content);
 const downloadPromise=page.waitForEvent("download");
 await recovery.getByRole("button",{name:"Unduh draf pemulihan"}).click();
 const download=await downloadPromise;
 assert.match(await require("node:fs/promises").readFile(await download.path(),"utf8"),new RegExp(draft));
 block=false;
 await recovery.getByRole("button",{name:"Pulihkan draf lokal"}).click();
 await page.waitForResponse(r=>r.url().endsWith(path)&&r.request().method()==="PATCH"&&r.status()===200);
 await canvas.getByText("Naskah tersimpan.",{exact:true}).waitFor();
 assert.equal((await db.chapter.findUnique({where:{id:chapter.id}})).content,draft);
 assert.equal(await page.evaluate(k=>sessionStorage.getItem(k),key),null);
 await page.reload();
 assert.equal(await field.inputValue(),draft);
 assert.equal(await recovery.count(),0);
 console.log("PASS failed save -> refresh -> explicit recovery -> download -> save -> cache cleared");
 const before=await db.chapter.findUnique({where:{id:chapter.id}});
 const remote="Perubahan penulis dari sesi kedua yang tidak boleh tertimpa.";
 const changed=await context.request.patch(origin+path,{data:{title:before.title,content:remote,expectedVersion:before.updatedAt.toISOString()}});
 assert.equal(changed.status(),200);
 const local="Draf konflik lokal yang harus tetap tersedia walau halaman dimuat ulang.";
 await field.fill(local);
 await canvas.getByRole("button",{name:"Muat versi server",exact:true}).waitFor();
 await page.reload();
 await recovery.getByText(/Versi server sudah berubah/).waitFor();
 await recovery.getByRole("button",{name:"Pulihkan draf lokal"}).click();
 await canvas.getByRole("button",{name:"Muat versi server",exact:true}).waitFor();
 assert.equal(await field.inputValue(),local);
 assert.equal((await db.chapter.findUnique({where:{id:chapter.id}})).content,remote);
 assert.equal(JSON.parse(await page.evaluate(k=>sessionStorage.getItem(k),key)).version,before.updatedAt.toISOString());
 await page.reload();
 await recovery.getByRole("button",{name:"Gunakan versi server",exact:true}).click();
 assert.equal(await field.inputValue(),remote);
 assert.equal(await page.evaluate(k=>sessionStorage.getItem(k),key),null);
 console.log("PASS stale recovered draft still gets 409; remote content preserved; explicit discard");
 for(const width of [320,375,390,768,1024,1440]){
  await page.setViewportSize({width,height:900});
  assert.equal(await canvas.evaluate(el=>el.scrollWidth<=el.clientWidth+1),true,"canvas overflow "+width);
 }
 console.log("PASS canvas widths 320/375/390/768/1024/1440 (not full-page accessibility certification)");
 await page.addInitScript(()=>{const original=Storage.prototype.setItem;Storage.prototype.setItem=function(key,value){if(this===window.sessionStorage&&key.startsWith("bcstudio:canvas-draft:"))throw new DOMException("Unavailable","QuotaExceededError");return original.call(this,key,value)}});
 await page.reload();
 await field.fill("Masih dapat disimpan meskipun penyimpanan browser tidak tersedia.");
 await canvas.getByText(/Draf belum dicadangkan di tab ini/).waitFor();
 await canvas.getByText("Naskah tersimpan.",{exact:true}).waitFor();
 assert.equal((await db.chapter.findUnique({where:{id:chapter.id}})).content,"Masih dapat disimpan meskipun penyimpanan browser tidak tersedia.");
 console.log("PASS storage failure is visible and does not block server save");
}
main().finally(async()=>{
 if(browser)await browser.close();
 if(book)await db.book.delete({where:{id:book.id}});
 if(user)await db.studioUser.delete({where:{id:user.id}});
 await db.$disconnect();
}).catch(error=>{console.error(error);process.exitCode=1});

