const replaceMarkdown=(source,key,value)=>{
 const lines=source.split(/\r?\n/);
 const header=lines.findIndex(x=>x.startsWith("## "+key+" "));
 assert(header>=0,"Missing stage field: "+key);
 const next=lines.findIndex((x,i)=>i>header&&x.startsWith("## "));
 return [...lines.slice(0,header+1),"",value,"",...lines.slice(next<0?lines.length:next)].join("\n");
};
async function applyMarkdown(page,container,edits){
 await container.getByRole("button",{name:"Unduh Markdown"}).click();
 const download=await page.waitForEvent("download",{timeout:15000}).catch(()=>null);
 if(!download)throw Error("Markdown download not available");
 let text=fs.readFileSync(await download.path(),"utf8");
 for(const [key,value] of Object.entries(edits))text=replaceMarkdown(text,key,value);
 await container.locator('input[type="file"]').setInputFiles({name:"stage-test.md",mimeType:"text/markdown",buffer:Buffer.from(text)});
 await container.getByRole("button",{name:/Terapkan ke form/}).click();
}
async function applyXlsx(page,container,values){
 const promise=page.waitForEvent("download");
 await container.getByRole("button",{name:"Unduh XLSX"}).click();
 const download=await promise;
 const zip=await JSZip.loadAsync(fs.readFileSync(await download.path()));
 let xml=await zip.file("xl/worksheets/sheet1.xml").async("string");
 const esc=value=>value.replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;");
 for(const [row,value] of Object.entries(values)){
  const regex=new RegExp('(<c r="C'+row+'"[^>]*><is><t xml:space="preserve">)[\\s\\S]*?(<\\/t><\\/is><\\/c>)');
  assert(regex.test(xml),"Missing Excel cell C"+row);
  xml=xml.replace(regex,(_,prefix,suffix)=>prefix+esc(value)+suffix);
 }
 zip.file("xl/worksheets/sheet1.xml",xml);
 const buffer=await zip.generateAsync({type:"nodebuffer"});
 await container.locator('input[type="file"]').setInputFiles({name:"stage-test.xlsx",mimeType:"application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",buffer});
 await container.getByRole("button",{name:/Terapkan ke form/}).click();
}
